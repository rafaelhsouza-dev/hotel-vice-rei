const engine: Record<Locale, EngineStrings> = { pt, en, es, fr };

export function getEngineStrings(locale: Locale): EngineStrings {
  return engine[locale];
}

export type { EngineStrings };

/** Turns a violation code into the sentence shown to the guest. */
export function violationText(
  s: EngineStrings,
  v: { code: string; nights?: number; days?: number; max?: number },
): string {
  const e = s.errors as Record<string, string | ((n: number) => string)>;
  const entry = e[v.code];
  if (typeof entry === "function") return entry(v.nights ?? v.days ?? v.max ?? 0);
  return entry ?? s.errors.server;
}
